VIBE_BY_CATEGORY = {  # modern 类别的典雅度（进 BOOK_ELEGANCE）
    "自然意象": 18, "现代文学": 20, "品格格言": 16, "新中式": 17,
}


def main():
    lib = namelib.load_chars()
    out, skipped = [], []
    for name, cat, note, gh in SEED:
        chars = list(name)
        miss = [c for c in chars if c not in lib]
        if miss:
            skipped.append((name, miss))
            continue
        ra, rb = lib[chars[0]], lib[chars[1]]
        out.append({
            "name": name, "chars": chars, "type": "modern",
            "source": {"book": cat, "title": note, "sentence": note,
                       "section": "现代来源"},
            "gender_hint": gh,
            "wuxing_pair": [ra["wuxing"], rb["wuxing"]],
            "tone_pair": [ra["tone"], rb["tone"]],
            "meaning_source": "curated",
        })
    with open(OUT, "w", encoding="utf-8") as f:
        for r in out:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"wrote {len(out)} modern names -> {OUT}")
    if skipped:
        print("[SKIP] 字库缺字：")
        for n, m in skipped:
            print(f"  {n} 缺 {'/'.join(m)}")


if __name__ == "__main__":
    main()
