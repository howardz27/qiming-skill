def tone3_of(ch, fix):
    if fix:
        return fix
    return pinyin(ch, style=Style.TONE3)[0][0]

def main():
    e = get_engine()
    out = []
    seen = set()
    for item in SURNAMES:
        name, rank = item
        if name in seen or rank is None:
            continue
        seen.add(name)
        py = tone3_of(name, SURNAME_PINYIN_FIX.get(name))
        kx, conf = e.kangxi(name)
        out.append({
            "surname": name, "pinyin_tone3": py,
            "pinyin": py.rstrip("12345"),
            "tone": int(py[-1]) if py[-1].isdigit() else 0,
            "kangxi": kx, "kangxi_conf": conf,
            "is_compound": False, "rank": rank,
        })
    for name, rank in COMPOUNDS:
        if name in seen:
            continue
        seen.add(name)
        py = COMPOUND_PINYIN_FIX.get(name) or " ".join(
            pinyin(c, style=Style.TONE3)[0][0] for c in name)
        kx = sum(e.kangxi(c)[0] or 0 for c in name)
        out.append({
            "surname": name, "pinyin_tone3": py,
            "pinyin": " ".join(p.rstrip("12345") for p in py.split()),
            "tone": [int(p[-1]) if p[-1].isdigit() else 0 for p in py.split()],
            "kangxi": kx, "kangxi_conf": "A",
            "is_compound": True, "rank": rank,
        })
    path = os.path.join(BASE, "knowledge", "surnames.json")
    with open(path, "w", encoding="utf-8") as f:
        json.dump({"comment": "百家姓(前300常见) + 常见复姓。rank为常见度序",
                   "surnames": out}, f, ensure_ascii=False, indent=1)
    print(f"surnames: {len(out)} (单姓 {sum(1 for x in out if not x['is_compound'])}, 复姓 {sum(1 for x in out if x['is_compound'])})")
    no_kx = [x["surname"] for x in out if not x["kangxi"]]
    print("无笔画:", no_kx[:10])

if __name__ == "__main__":
    main()
